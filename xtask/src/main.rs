use std::env;
use std::error::Error;
use std::fs;
use std::io;
use std::path::Path;
use std::process::{Command, ExitCode};

const BINDGEN_VERSION: &str = "0.2.129";
const LOADER: &str = r#"// Generated by cargo run -p xtask -- web; application logic lives in ui/src/.
import init from './pkg/maimai_ui.js';
init().catch(() => {
  const message = document.getElementById('message');
  message.textContent = '界面加载失败，请使用支持 WebAssembly 的浏览器并重新启动服务。';
  message.classList.add('error');
  message.hidden = false;
});
"#;

fn run(command: &mut Command) -> Result<(), Box<dyn Error>> {
    let status = command.status()?;
    if !status.success() {
        return Err(io::Error::other(format!("构建命令失败：{command:?}（{status}）")).into());
    }
    Ok(())
}

fn build_web() -> Result<(), Box<dyn Error>> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).parent().unwrap();
    let version = Command::new("wasm-bindgen").arg("--version").output().map_err(|_| {
        io::Error::other(format!("先运行 cargo install wasm-bindgen-cli --version {BINDGEN_VERSION} --locked"))
    })?;
    if !version.status.success()
        || String::from_utf8_lossy(&version.stdout).trim().strip_prefix("wasm-bindgen ") != Some(BINDGEN_VERSION)
    {
        return Err(io::Error::other(format!("需要 wasm-bindgen-cli {BINDGEN_VERSION}，请安装匹配版本。" )).into());
    }
    run(Command::new("cargo").current_dir(root).args([
        "build", "--locked", "--release", "-p", "maimai-ui", "--target", "wasm32-unknown-unknown",
    ]))?;
    let target = env::var_os("CARGO_TARGET_DIR").map(Into::into).unwrap_or_else(|| root.join("target"));
    let target = if target.is_absolute() { target } else { root.join(target) };
    let output = root.join("web/pkg");
    fs::create_dir_all(&output)?;
    run(Command::new("wasm-bindgen").current_dir(root)
        .arg(target.join("wasm32-unknown-unknown/release/maimai_ui.wasm"))
        .args(["--target", "web", "--no-typescript", "--out-name", "maimai_ui", "--out-dir"])
        .arg(output))?;
    fs::write(root.join("web/loader.js"), LOADER)?;
    println!("已更新 web/pkg 与 web/loader.js；运行 cargo build --release --locked 嵌入界面。");
    Ok(())
}

fn main() -> ExitCode {
    let mut args = env::args().skip(1);
    if args.next().as_deref() != Some("web") || args.next().is_some() {
        eprintln!("用法：cargo run --locked -p xtask -- web");
        return ExitCode::FAILURE;
    }
    match build_web() {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("错误：{error}");
            ExitCode::FAILURE
        }
    }
}
